"""市场事实与单位定义——不是"可调参数"，是 A 股机制本身的取值。

这个模块和 ``configs/params.yaml`` 的分工：

* ``params.yaml`` 放**有人可能想改**的数：阈值、窗口、上限。改它不需要动代码。
* 本模块放**改了就是错**的数：1 手 100 股、1 万 = 10000 元、一年约 252 个交易日、
  价格最小变动 0.01 元。这些不是策略偏好，是交易所规则和单位定义。

为什么仍然要集中：``252`` 曾经在 10 个文件里各写一遍，``PRICE_EPS`` 有 Decimal
和 float 两个版本（``kernel.microstructure`` 与 ``adapters.derive``），``BPS``
在 ``tca`` 里又定义了一次。同一个事实写两遍，改一处就是制造一个静默的偏差——
涨跌停比较容差差一个数量级，会让"开板"判定整体偏移，而没有任何报错。

引用来源写在各常量后面，便于核对；不确定的地方宁可写宽一点也不要猜。
"""

from __future__ import annotations

from decimal import Decimal

# ── 交易单位 ────────────────────────────────────────────────────────────────
# 沪深主板/创业板/科创板：买入以 100 股（1 手）为单位；科创板另要求单笔不少于
# 200 股，但增量仍是 1 股，这里只管"1 手"这个展示与估算单位。
SHARES_PER_LOT = 100
# 可转债 1 手 = 10 张，面值 100 元/张。
CB_SHARES_PER_LOT = 10

# ── 金额单位 ────────────────────────────────────────────────────────────────
# 行情源里 amount 常以"万元"计（tushare daily.amount 单位是千元，另说），
# circ_mv/total_mv 是万元。乘错一次就是 1 万倍的仓位。
CNY_PER_WAN = 10_000
CNY_PER_YI = 100_000_000

# ── 价格 ────────────────────────────────────────────────────────────────────
# 最小报价单位。所有"价格是否等于涨停价"的判断都要先过这个容差：
# 涨停价由昨收 × (1+幅度) 四舍五入到分，直接用 == 比较会漏掉半分钱。
PRICE_TICK = Decimal("0.01")
# 比较容差取 1 分钱的十分之一，比任何真实的报价差都小，又足以吸收浮点误差。
# 这是**唯一**一份：`microstructure` 曾经自己又写了一遍，两份一旦分叉，
# "开板"判定会整体偏移而没有任何报错。
PRICE_EPS = Decimal("0.001")
# 可转债最小报价单位是 0.001 元，不是 0.01 元。
CB_PRICE_TICK = Decimal("0.001")

# ── 精度与面值 ──────────────────────────────────────────────────────────────
# 金额记账到分，成本价（含费用摊薄）记到 4 位——再少会让多次部分成交的成本
# 累积误差超过一分钱，再多则没有对应的经济含义。
MONEY_QUANT = Decimal("0.01")
COST_BASIS_QUANT = Decimal("0.0001")
# 可转债面值 100 元/张：到期赎回与票息都以它为基数。
CB_PAR = Decimal(100)

# ── 时间 ────────────────────────────────────────────────────────────────────
# 年化因子。A 股每年约 242–244 个交易日，业界惯例用 252（美股口径）做年化，
# 本仓库一直沿用 252；这里固定下来是为了让所有波动率/夏普可比，不是为了精确。
# 若改成 244，全仓库的年化数字会一起变——这正是它必须只有一个来源的原因。
TRADING_DAYS_PER_YEAR = 252

# ── 比率 ────────────────────────────────────────────────────────────────────
# 1 个基点 = 万分之一。佣金"万 2.5" = 2.5 bps。
BPS = Decimal(10000)

# ── 涨跌停幅度 ──────────────────────────────────────────────────────────────
# 这些是交易所规则，不是策略偏好。放在这里而不是各模块里，是因为它曾经有
# 四份：``adapters.symbols.limit_pct``（唯一正确的一份）、
# ``kernel.models.Instrument.limit_pct`` 的默认值、``trading.external.limit_pct``
# （漏了 920xxx、把 ST 的 5% 套到创业板）、``trading.realtime._limits``（四舍五入
# 用了一半进位）。判错档位的后果不是显示错误：它决定开盘一字板是否拒绝买入，
# 也决定监控是不是对一只只跌了 5% 的票喊"跌停"。
#
# 分类逻辑（哪个代码属于哪个板、是不是 ST、是不是未股改）留在
# ``adapters/symbols.limit_pct``，因为那需要知道代码前缀和简称；
# 这里只定义幅度本身。
#
# **三档都会过期，所以它们都带日期。**
#
# 1. **主板 ST 是 10%，不是 5%。** 沪深北三大交易所 2026-04-24 修订《交易规则》，
#    沪深主板风险警示股票（ST/*ST）的涨跌幅比例由 5% 调整为 10%，与主板普通股统一，
#    2026-07-06 起施行（创业板/科创板 ST 仍 20%、北交所 *ST 仍 30%，均不变）。
#    本仓库曾一直用 5%，于是 2026-07-06 之后的每一只主板 ST 都带着半个错的带宽：
#    实盘监控在 -5% 就喊"跌停"（真跌停在 -10%），盘中撮合算出的涨跌停价也是错的。
#    证据在本仓库自己的数据里——``data/parquet/stk_limit/2026.parquet`` 里主板
#    ±5% 带宽的占比：1–6 月 3.6%–5.0%，7 月 0.55%，8–10 月 0.03%。
#
# 2. **未完成股权分置改革的股票恒为 5%。** 上交所《关于对未股改股票实施差异化交易
#    监管的通知》（上证发〔2014〕3号，现行有效）：未股改公司简称前冠 "S"，
#    价格涨跌幅限制为 ±5%。这条**优先于**风险警示规则——佳通轮胎 2023-05-16 的
#    公告写明"撤销退市风险警示及其他风险警示后……日涨跌幅限制不变，仍为 5%"。
#    本地数据同样如此：600182.SH（S佳通，2021–2023 年曾为 SST佳通/S*ST佳通）
#    三年 700 多个交易日的带宽全是 5%。
#
# 3. 2026-07-06 之前的主板 ST 是 5%。历史查询必须用当时的规则去解释当天的数据，
#    否则就是拿今天的制度解释昨天的行情。
#
# 这类数会过期，所以它有一道反向检查：``tests/kernel/test_limit_pct_rules.py``
# 直接拿本地 stk_limit 反查本模块——交易所改规则而这里没跟上，测试会红。
LIMIT_PCT_MAIN = Decimal("0.10")
LIMIT_PCT_ST = Decimal("0.10")            # 主板 ST：2026-07-06 起由 5% 改为 10%
LIMIT_PCT_ST_LEGACY = Decimal("0.05")     # 主板 ST：2026-07-06 之前
LIMIT_PCT_UNREFORMED = Decimal("0.05")    # 未完成股改（S 开头），恒为 5%
LIMIT_PCT_GROWTH = Decimal("0.20")       # 创业板、科创板（ST 同样 20%）
LIMIT_PCT_BSE = Decimal("0.30")          # 北交所（*ST 同样 30%）
LIMIT_PCT_CB = Decimal("0.20")           # 可转债（存量债；上市首日更宽，本台不参与）
LIMIT_PCT_DEFAULT = LIMIT_PCT_MAIN

#: 主板 ST 涨跌幅由 5% 调整为 10% 的生效日（YYYYMMDD）。
ST_BAND_CHANGE_DATE = "20260706"

#: 数据里出现过的全部涨跌幅档，从小到大。
#:
#: 5% 仍然在列表里，有两个原因：未完成股改的股票恒为 5%，以及 2026-07-06
#: 之前的主板 ST 是 5%。研究层按"幅度"给一只票归档（``research.tape_state.
#: band_of``），所以这份列表要跟着**数据里实际存在的档**走，而不是跟着
#: "当前规则"走——用今天的规则去分类历史行情，会把 5% 的票判成"不属于任何
#: 一档"而被丢掉。
LIMIT_BANDS = (Decimal("0.05"), Decimal("0.10"), Decimal("0.20"), Decimal("0.30"))
