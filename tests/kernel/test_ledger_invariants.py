CAL = TradingCalendar.always()
MODEL = BarExecutionModel()
STOCK = "600000.SH"
BOND = "113050.SH"

INSTRUMENTS = {
    STOCK: Instrument(STOCK, min_qty=100, qty_step=100, limit_pct=D("0.10")),
    # T+0, 10-unit lots, 0.001 tick: the settlement branch and the price
    # precision branch are both exercised by the same run.
    BOND: Instrument(BOND, min_qty=10, qty_step=10, price_tick=D("0.001"),
                     t_plus=0, limit_pct=D("0.20"),
                     stamp_duty=D("0"), transfer_fee=D("0")),
}

OPENING_CASH = D("20000")


def bar_for(symbol: str, step: int, *, thin: bool = False, sealed: bool = False) -> Bar:
    """A deterministic bar, so a failing example is replayable from its ops."""
    inst = INSTRUMENTS[symbol]
    pre = D("20.00")
    up, down = inst.band(pre)
    tick = inst.price_tick
    base = D("20.00") if not sealed else up
    open_ = base.quantize(tick)
    high = min(up, open_ + D("0.50"))
    low = max(down, open_ - D("0.50"))
    close = open_ if sealed else (open_ + D("0.10"))
    volume = 1000 if thin else 10_000_000
    return Bar(
        symbol=symbol,
        ts=datetime(2026, 3, 2, 9, 35, tzinfo=SHANGHAI) + timedelta(minutes=step * 5),
        open=open_, high=high, low=low, close=min(close, high), pre_close=pre,
        volume=volume, amount=D(volume) * open_,
        up_limit=up, down_limit=down,
        prior_volume=volume,
    )


def assert_invariants(ledger: Ledger, opening: Decimal, tag: str = "") -> None:
    acc = ledger.account
    tol = Decimal("0.05") * max(1, len(ledger.fills))

    assert acc.cash_available >= 0, f"{tag} cash went negative: {acc.cash_available}"
    assert acc.cash_frozen >= 0, f"{tag} frozen cash negative: {acc.cash_frozen}"

    for symbol, pos in acc.positions.items():
        assert pos.is_consistent(), (
            f"{tag} {symbol}: total {pos.total_qty} != available {pos.available_qty} "
            f"+ frozen {pos.frozen_qty} + locked {pos.locked_qty}"
        )

    open_buy = sum((o.frozen_cash for o in ledger.oms.open_orders()
                    if o.side is Side.BUY), D("0"))
    assert money(open_buy) == acc.cash_frozen, (
        f"{tag} frozen cash {acc.cash_frozen} != open orders {money(open_buy)}"
    )

    open_sell: dict[str, int] = {}
    for order in ledger.oms.open_orders():
        if order.side is Side.SELL:
            open_sell[order.symbol] = open_sell.get(order.symbol, 0) + order.frozen_shares
    for symbol, qty in open_sell.items():
        pos = acc.peek(symbol)
        assert pos is not None and pos.frozen_qty == qty, (
            f"{tag} {symbol}: frozen qty {getattr(pos, 'frozen_qty', None)} "
            f"!= open sell orders {qty}"
        )

    order_fees = sum((o.fees_paid for o in ledger.oms.orders.values()), D("0"))
    fill_fees = sum((f.fees for f in ledger.fills), D("0"))
    assert abs(acc.fees_paid - order_fees) <= tol, (
        f"{tag} fees_paid {acc.fees_paid} != order fees {order_fees}"
    )
    assert abs(acc.fees_paid - fill_fees) <= tol, (
        f"{tag} fees_paid {acc.fees_paid} != fill fees {fill_fees}"
    )

    book = sum((D(p.total_qty) * p.avg_cost for p in acc.positions.values()), D("0"))
    assert abs((acc.cash_total() + book) - (opening + acc.realized_pnl)) <= tol, (
        f"{tag} cash+book {acc.cash_total() + book} != "
        f"opening+realized {opening + acc.realized_pnl}"
    )

    marked = acc.cash_total() + sum(
        (D(p.total_qty) * p.last_price for p in acc.positions.values()), D("0"))
    assert money(marked) == acc.equity(), f"{tag} equity disagrees with cash + marks"


# ── 1. 结算语义：T+1 锁是显式的 ─────────────────────────────────────────────
def test_a_t_plus_one_buy_is_locked_not_available_and_not_frozen():
    ledger = Ledger.fresh("20000")
    order = ledger.submit(Intent(STOCK, Side.BUY, qty=100), bar_for(STOCK, 0).ts,
                          INSTRUMENTS[STOCK], bar_for(STOCK, 0), CAL)
    result = MODEL.match(order, bar_for(STOCK, 0), INSTRUMENTS[STOCK],
                         bar_for(STOCK, 0).ts, CAL)
    assert result.filled, result.detail
    ledger.apply_fill(order, result.fill)

    pos = ledger.account.peek(STOCK)
    assert (pos.total_qty, pos.available_qty, pos.frozen_qty, pos.locked_qty) == (
        100, 0, 0, 100
    )
    assert pos.unsettled_qty == 100
    assert_invariants(ledger, OPENING_CASH)

    ledger.settle()
    assert (pos.total_qty, pos.available_qty, pos.frozen_qty, pos.locked_qty) == (
        100, 100, 0, 0
    )
    assert_invariants(ledger, OPENING_CASH)


def test_a_t_plus_zero_buy_is_available_immediately():
    """A convertible settles T+0, so nothing may be locked."""
    ledger = Ledger.fresh("20000")
    bar = bar_for(BOND, 0)
    order = ledger.submit(Intent(BOND, Side.BUY, qty=100), bar.ts,
                          INSTRUMENTS[BOND], bar, CAL)
    result = MODEL.match(order, bar, INSTRUMENTS[BOND], bar.ts, CAL)
    assert result.filled, result.detail
    ledger.apply_fill(order, result.fill)

    pos = ledger.account.peek(BOND)
    assert (pos.total_qty, pos.available_qty, pos.locked_qty) == (100, 100, 0)


def test_the_lock_survives_a_snapshot_round_trip():
    ledger = Ledger.fresh("20000")
    bar = bar_for(STOCK, 0)
    order = ledger.submit(Intent(STOCK, Side.BUY, qty=100), bar.ts,
                          INSTRUMENTS[STOCK], bar, CAL)
    ledger.apply_fill(order, MODEL.match(order, bar, INSTRUMENTS[STOCK], bar.ts, CAL).fill)

    restored = Ledger.from_snapshot(ledger.snapshot())
    pos = restored.account.peek(STOCK)
    assert (pos.total_qty, pos.available_qty, pos.locked_qty) == (100, 0, 100)
    assert restored.reconcile(ledger.snapshot()) == []


def test_an_old_snapshot_without_the_lock_derives_it():
    """A snapshot written before ``locked_qty`` existed must not unlock on restore."""
    snapshot = {
        "cash_available": "18994.99", "cash_frozen": "0", "cash_withdrawable": "18994.99",
        "realized_pnl": "0", "fees_paid": "5.01", "dividend_income": "0",
        "peak_equity": "20000", "order_seq": 0,
        "positions": {STOCK: {"total_qty": 100, "available_qty": 0, "frozen_qty": 0,
                              "avg_cost": "10.0000", "last_price": "10.00",
                              "realized_pnl": "0", "sleeve": "CORE"}},
        "orders": {}, "order_records": [], "fills": [],
    }

    restored = Ledger.from_snapshot(snapshot)
    pos = restored.account.peek(STOCK)
    assert pos.locked_qty == 100, "the unnamed difference is the T+1 lock"
    assert pos.is_consistent()


def test_reconcile_reports_a_tampered_lock():
    ledger = Ledger.fresh("20000")
    snapshot = ledger.snapshot()
    snapshot["positions"][STOCK] = {
        "total_qty": 100, "available_qty": 0, "frozen_qty": 0, "locked_qty": 40,
        "avg_cost": "10.0000", "last_price": "10.00", "realized_pnl": "0",
        "sleeve": "CORE",
    }
    ledger.account.positions[STOCK] = Position(
        symbol=STOCK, total_qty=100, locked_qty=100, avg_cost=D("10")
    )

    diffs = ledger.reconcile(snapshot)
    assert any("locked_qty" in d for d in diffs), diffs


def test_a_redeemed_bond_clears_its_lock():
    account = Ledger.fresh("20000").account
    account.positions[BOND] = Position(
        symbol=BOND, total_qty=10, available_qty=0, locked_qty=10, avg_cost=D("100")
    )

    CBMaturity(symbol=BOND, delist_date=datetime(2026, 3, 2).date()).apply(account)

    pos = account.peek(BOND)
    assert pos.total_qty == 0 and pos.locked_qty == 0
    assert pos.is_consistent()


# ── 2. 任意操作序列下的恒等式 ────────────────────────────────────────────────
OPS = st.lists(
    st.tuples(
        st.sampled_from([STOCK, BOND]),
        st.sampled_from([Side.BUY, Side.SELL]),
        st.integers(1, 8),          # lots
        st.booleans(),              # limit order?
        st.integers(-6, 6),         # limit offset in ticks from the open
        st.booleans(),              # thin session -> capacity cap binds
        st.booleans(),              # settle after this step
        st.booleans(),              # cancel every open order instead of matching
    ),
    min_size=1,
    max_size=25,
)


@given(OPS)
@settings(
    max_examples=60,
    deadline=None,
    derandomize=True,
    suppress_health_check=[HealthCheck.function_scoped_fixture],
)
def test_the_books_balance_after_any_sequence_of_orders(ops):
    """Buy, sell, cancel, settle, partially fill, hit the cap and the lot rules.

    The assertion is not "this order filled" but "whatever happened, the books
    still balance" — which is the property a real ledger has to have.
    """
    ledger = Ledger.fresh("20000")
    opening = ledger.account.cash_available

    for step, (symbol, side, lots, is_limit, offset, thin, settle, cancel) in enumerate(ops):
        inst = INSTRUMENTS[symbol]
        bar = bar_for(symbol, step, thin=thin)
        ts = bar.ts
        limit = None
        if is_limit:
            limit = (bar.open + D(offset) * inst.price_tick).quantize(inst.price_tick)
            limit = min(max(limit, bar.down_limit), bar.up_limit)

        order = ledger.submit(
            Intent(symbol, side, qty=lots * max(1, inst.min_qty),
                   order_type=OrderType.LIMIT if is_limit else OrderType.MARKET,
                   limit_price=limit, client_order_id=f"s{step}"),
            ts, inst, bar, CAL,
        )
        assert order.status in {OrderStatus.NEW, OrderStatus.REJECTED}
        assert_invariants(ledger, opening, f"step {step} after submit")

        if cancel:
            for open_order in list(ledger.oms.open_orders()):
                ledger.cancel(open_order.order_id, ts, CAL)
        else:
            for open_order in list(ledger.oms.open_orders()):
                if open_order.symbol != symbol:
                    continue
                matched = MODEL.match(open_order, bar, inst, ts, CAL)
                if matched.fill is not None:
                    ledger.apply_fill(open_order, matched.fill)
        assert_invariants(ledger, opening, f"step {step} after match/cancel")

        if settle:
            ledger.expire_ioc(ts)
            ledger.expire_day_orders(ts)
            ledger.settle()
            assert_invariants(ledger, opening, f"step {step} after settle")

    restored = Ledger.from_snapshot(ledger.snapshot())
    assert restored.reconcile(ledger.snapshot()) == []
    assert_invariants(restored, opening, "after restore")


# ── 3. 公司行为不破坏恒等式 ──────────────────────────────────────────────────
def test_a_cash_and_stock_dividend_keeps_the_books_balanced():
    ledger = Ledger.fresh("20000")
    bar = bar_for(STOCK, 0)
    order = ledger.submit(Intent(STOCK, Side.BUY, qty=500), bar.ts,
                          INSTRUMENTS[STOCK], bar, CAL)
    ledger.apply_fill(order, MODEL.match(order, bar, INSTRUMENTS[STOCK], bar.ts, CAL).fill)
    ledger.settle()
    before = ledger.account.cash_total()

    action = CorporateAction(
        symbol=STOCK, ex_date=datetime(2026, 3, 2).date(),
        cash_div_per_share=D("0.30"), stock_div_per_share=D("0.20"),
    )
    result = action.apply(ledger.account)

    assert result["applied"] is True
    pos = ledger.account.peek(STOCK)
    assert pos.total_qty == 600, "one bonus share per five held"
    assert ledger.account.cash_total() - before == D("150.00")
    assert_invariants(ledger, OPENING_CASH)


