"""The ledger's accounting contract, checked as invariants rather than examples.

Every bug this file guards against is the same shape: a number that is right on
the happy path and wrong in a corner. Hand-written cases covered the corners
someone thought of; these check the identity that must hold at *every* point in
the lifecycle, over operation sequences nobody enumerated:

* every share is sellable, reserved, or locked — never in two of those at once
  and never in none of them;
* reserved cash equals what the live orders say is reserved;
* fees charged to the account equal the fees on the orders equal the fees on the
  fills;
* ``cash + book value`` equals ``opening capital + realized`` — buying cannot
  create or destroy book value, only move it between cash and shares;
* a restarted ledger is the same ledger.

The sequences are generated by ``hypothesis`` with ``derandomize=True`` so a
failure is reproducible from its seed alone. That matters here more than in a
normal test: a flaky ledger test would be "fixed" by rerunning it.
"""

