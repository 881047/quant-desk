@pytest.mark.parametrize("qty", [100, 1000])
def test_a_fill_cannot_exceed_the_orders_remaining_quantity(qty):
    ledger = Ledger.fresh("200000")
    bar = bar_for(STOCK, 0)
    order = ledger.submit(Intent(STOCK, Side.BUY, qty=qty), bar.ts,
                          INSTRUMENTS[STOCK], bar, CAL)
    oversized = Fill(
        fill_id="too-big", order_id=order.order_id, symbol=STOCK, side=Side.BUY,
        qty=qty + 100, price=bar.open, fees=D("5"), ts=bar.ts,
    )
    with pytest.raises(FillRejected, match="exceeds remaining") as err:
        ledger.apply_fill(order, oversized)
    assert err.value.code == "FILL_QTY_EXCEEDS", (
        "the refusal must carry a code, not only an English sentence")
